# %% [markdown]
# # Process

# %%
def process(parsed):
    ics(parsed)
    buffer = [0]
    pos = 0

    for n in range(1, 2018):
        pos = (pos + parsed) % len(buffer) + 1
        buffer.insert(pos, n)
        if n < 10:
            ics(n, pos, len(buffer), buffer[:10])

    return buffer[pos+1]


# %%
def part1(inp):
    parsed = parse(inp)
    result = process(parsed)
    print_result(result)


