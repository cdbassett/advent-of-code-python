def parse_data(inp):
    patterns, designs = inp.split("\n\n")
    return patterns.split(", "), designs.split("\n")


# %% [markdown]
# # Process

# %%
def process(parsed):
    patterns, designs = parsed
    ics(patterns, designs)
    ic(len(patterns), len(designs))

    @cache
    def design_possible(design):
        return not design or any(design.startswith(pattern) and design_possible(design[len(pattern):]) for pattern in patterns)
        
    return sum(1 for design in designs if design_possible(design))


# %%
def part1(inp):
    parsed = parse_data(inp)
    result = process(parsed)
    print_result(result)


# %% [markdown]
# # Process2

# %%
def process2(parsed):
    patterns, designs = parsed
    
    @cache
    def possible_count(design):
        if not design:
            return 1

        return sum(possible_count(design[len(pattern):]) for pattern in patterns if design.startswith(pattern))

    return sum(possible_count(design) for design in designs)


# %%
def part2(inp):
    parsed = parse_data(inp)
    result = process2(parsed)
    print_result(result)


