# # Parse

# %%
def parse_line(line):
    key, *outs = line.split()
    return key[:-1], tuple(outs)

def parse_data(inp):
    return seq(inp.strip().split("\n")).map(parse_line).list()


# %% [markdown]
# # Process

# %%
def process(parsed):
    path_dict = dict(parsed)
    ics(path_dict)

    @cache
    def count_paths(key):
        if key == "out":
            return 1
            
        outs = path_dict[key]
        return sum(count_paths(key) for key in outs)
    
    return count_paths("you")


# %%
def part1(inp):
    parsed = parse_data(inp)
    result = process(parsed)
    print_result(result)


# %% [markdown]
# # Process2

# %%
def process2(parsed):
    path_dict = dict(parsed)
    ics(path_dict)

    @cache
    def count_paths(key, visited=0):
        if key == "out":
            return 1 if visited == 3 else 0

        if key == "fft":
            visited |= 1
        
        if key == "dac":
            visited |= 2
            
        outs = path_dict[key]
        return sum(count_paths(key, visited) for key in outs)
    
    return count_paths("svr")


# %%
def part2(inp):
    parsed = parse_data(inp)
    result = process2(parsed)
    print_result(result)


